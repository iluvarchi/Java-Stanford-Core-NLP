    private void initialSetup() {
        this.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        lemmatization(txtinputCabiles);
        this.setCursor(Cursor.getDefaultCursor());
    }

    private void lemmatization(JTextArea txt_Cabiles) {
        String text_Cabiles = txt_Cabiles.getText();
        Properties props_Cabiles = new Properties(); // Set pipeline properties
        props_Cabiles.setProperty("annotators", "tokenize, ssplit, pos, lemma");
        StanfordCoreNLP pipeline_Cabiles = new StanfordCoreNLP(props_Cabiles); // Create StanfordCoreNLP Pipeline
        Annotation document_Cabiles = new Annotation(text_Cabiles); // Annotate the text
        pipeline_Cabiles.annotate(document_Cabiles);
        
        txtresult_Cabiles.setText("");
        for (CoreMap sentence_Cabiles: document_Cabiles.get(CoreAnnotations.SentencesAnnotation.class)) 
        {
            for (CoreLabel token_Cabiles : sentence_Cabiles.get(CoreAnnotations.TokensAnnotation.class)) 
            {
                String word_Cabiles = token_Cabiles.get(CoreAnnotations.TextAnnotation.class); // Get the word
                String lemma_Cabiles = token_Cabiles.get(CoreAnnotations.LemmaAnnotation.class); // Get the lemma
                txtresult_Cabiles.append(word_Cabiles + " -> " + lemma_Cabiles + "\n");
            }
        }
    }
